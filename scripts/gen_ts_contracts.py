"""Generate the web's TypeScript contract types from the pydantic models (CONTRACTS §4).

Usage:
    .venv/bin/python scripts/gen_ts_contracts.py           # write src/web/src/contracts/generated/*.ts
    .venv/bin/python scripts/gen_ts_contracts.py --check   # exit 1 if any file would change (CI)

One ``<module>.ts`` per contracts module that defines models, plus ``index.ts``. Interfaces keep the Python names
and snake_case fields. Mapping: ``Literal`` -> union of literals (a named alias when the module defines one);
int/float -> number; bool -> boolean; str/datetime/date/SecretStr -> string; list -> ``T[]``; dict ->
``Record<string, T>`` (``Partial<Record<K, T>>`` for literal keys); nested models -> imported interfaces; ``Any`` ->
``unknown``. Every field is required: nullable fields are ``T | null`` because the API always sends ``null``
(CONTRACTS §1.7 rule 6). Discriminated unions (``Annotated[A | B, Field(discriminator=...)]``) become union types.
``events.ts`` also gets ``EventPayloads`` and ``PERSISTED_EVENT_TYPES`` / ``EPHEMERAL_EVENT_TYPES``.
"""

from __future__ import annotations

import argparse
import ast
import datetime as dt
import enum
import importlib
import sys
import types
import typing
import uuid
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Annotated, Any, Literal, get_args, get_origin

from pydantic import AwareDatetime, BaseModel, NaiveDatetime, SecretStr

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "src"))

OUT_DIR = REPO_ROOT / "src" / "web" / "src" / "contracts" / "generated"
MODULES = ("common", "menu", "orders", "kitchen", "inventory", "gm", "ledger", "events", "api", "ws")
HEADER = "// GENERATED by scripts/gen_ts_contracts.py — do not edit"
_STRINGY = (str, dt.datetime, dt.date, dt.time, AwareDatetime, NaiveDatetime, SecretStr, uuid.UUID, Path)


def _ts_literal(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | float):
        return repr(value)
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    raise TypeError(f"unsupported literal {value!r}")


def _literal_key(values: Sequence[Any]) -> tuple[tuple[str, Any], ...]:
    # typing caches Literals by value and 1 == True, so aliases are matched on (type, value) pairs
    return tuple((type(v).__name__, v) for v in values)


def _union(parts: list[str]) -> str:
    unique = list(dict.fromkeys(parts))
    if "null" in unique:  # null last: "string | null"
        unique = [p for p in unique if p != "null"] + ["null"]
    return " | ".join(unique)


class Registry:
    """Every contracts module's models, literal aliases and discriminated unions, by name."""

    def __init__(self, module_names: Sequence[str]) -> None:
        self.modules = {name: importlib.import_module(f"restaurantos.contracts.{name}") for name in module_names}
        self.models: dict[str, list[type[BaseModel]]] = {}
        self.literals: dict[str, list[tuple[str, tuple[Any, ...]]]] = {}
        self.unions: dict[str, list[tuple[str, tuple[type[BaseModel], ...]]]] = {}
        self.home: dict[str, str] = {}  # exported name -> module
        literal_names: dict[tuple[tuple[str, Any], ...], list[tuple[str, str]]] = {}
        for mod_name, module in self.modules.items():
            self.models[mod_name] = [
                obj for name, obj in vars(module).items()
                if isinstance(obj, type) and issubclass(obj, BaseModel) and obj.__module__ == module.__name__
                and not name.startswith("_") and obj.__name__ == name and obj.__name__ != "Model"
            ]
            self.literals[mod_name], self.unions[mod_name] = [], []
            for name in _top_level_assignments(Path(module.__file__)):
                obj = getattr(module, name, None)
                if get_origin(obj) is Literal:
                    self.literals[mod_name].append((name, get_args(obj)))
                    literal_names.setdefault(_literal_key(get_args(obj)), []).append((mod_name, name))
                elif get_origin(obj) is Annotated and _is_model_union(get_args(obj)[0]):
                    self.unions[mod_name].append((name, get_args(get_args(obj)[0])))
            names = ([m.__name__ for m in self.models[mod_name]] + [n for n, _ in self.literals[mod_name]]
                     + [n for n, _ in self.unions[mod_name]])
            for name in names:
                if name in self.home:
                    raise SystemExit(f"name clash: {name} is exported by both {self.home[name]} and {mod_name}")
                self.home[name] = mod_name
        # a literal annotation maps back to its alias only when exactly one alias has those values
        self.alias_of = {key: owners[0] for key, owners in literal_names.items() if len(owners) == 1}


def _top_level_assignments(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names = []
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            names.append(node.targets[0].id)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.value is not None:
            names.append(node.target.id)
    return names


def _is_model_union(tp: Any) -> bool:
    return get_origin(tp) in (typing.Union, types.UnionType) and all(
        isinstance(a, type) and issubclass(a, BaseModel) for a in get_args(tp))


class ModuleWriter:
    """Renders one contracts module; ``imports`` collects the names it needs from sibling modules."""

    def __init__(self, registry: Registry, module_name: str) -> None:
        self.reg = registry
        self.module = module_name
        self.imports: dict[str, set[str]] = {}

    def ref(self, name: str) -> str:
        home = self.reg.home.get(name)
        if home is None:
            raise SystemExit(f"{self.module}: {name} is not defined in any generated contracts module")
        if home != self.module:
            self.imports.setdefault(home, set()).add(name)
        return name

    def ts(self, tp: Any) -> str:
        origin, args = get_origin(tp), get_args(tp)
        if tp is None or tp is type(None):
            return "null"
        if origin is Annotated:
            return self.ts(args[0])
        if origin in (typing.Union, types.UnionType):
            return _union([self.ts(a) for a in args])
        if origin is Literal:
            owner = self.reg.alias_of.get(_literal_key(args))
            return self.ref(owner[1]) if owner else _union([_ts_literal(v) for v in args])
        if origin in (list, set, frozenset, Sequence) or (origin is tuple and len(args) == 2 and args[1] is ...):
            inner = self.ts(args[0]) if args else "unknown"
            return f"({inner})[]" if " " in inner else f"{inner}[]"
        if origin is tuple:
            return "[" + ", ".join(self.ts(a) for a in args) + "]"
        if origin in (dict, Mapping):
            key, value = (args or (str, Any))
            if get_origin(key) is Literal:
                return f"Partial<Record<{self.ts(key)}, {self.ts(value)}>>"
            return f"Record<string, {self.ts(value)}>"
        if tp is Any or tp is object:
            return "unknown"
        if isinstance(tp, type):
            if issubclass(tp, BaseModel):
                return self.ref(tp.__name__)
            if issubclass(tp, enum.Enum):
                return _union([_ts_literal(m.value) for m in tp])
            if issubclass(tp, bool):
                return "boolean"
            if issubclass(tp, int | float):
                return "number"
            if issubclass(tp, _STRINGY):
                return "string"
        raise SystemExit(f"{self.module}: no TypeScript mapping for {tp!r}")

    def interface(self, model: type[BaseModel]) -> str:
        fields = model.model_fields
        if not fields:
            return f"export type {model.__name__} = Record<string, never>"
        lines = [f"export interface {model.__name__} {{"]
        for name, info in fields.items():
            key = info.serialization_alias or info.alias or name
            lines.append(f"  {key}: {self.ts(info.annotation)}")
        lines.append("}")
        return "\n".join(lines)

    def render(self) -> str:
        blocks = []
        for name, values in self.reg.literals[self.module]:
            blocks.append(_alias_block(name, [_ts_literal(v) for v in values]))
        for name, members in self.reg.unions[self.module]:
            blocks.append(_alias_block(name, [self.ref(m.__name__) for m in members]))
        blocks.extend(self.interface(model) for model in self.reg.models[self.module])
        if self.module == "events":
            blocks.extend(self.event_blocks())
        head = [HEADER, f"// Source: src/restaurantos/contracts/{self.module}.py"]
        imports = [_import_line(sorted(self.imports[mod]), mod) for mod in MODULES if mod in self.imports]
        return "\n".join(head) + "\n\n" + ("\n".join(imports) + "\n\n" if imports else "") + "\n\n".join(blocks) + "\n"

    def event_blocks(self) -> list[str]:
        events = self.reg.modules["events"]
        rows = [f"    '{t}': {self.ts(model)}" for t, (_, model) in events.EVENT_SPECS.items()]
        payloads = "export type EventPayloads = {\n  [K in EventType]: {\n" + "\n".join(rows) + "\n  }[K]\n}"
        return [payloads, _const_tuple("PERSISTED_EVENT_TYPES", events.PERSISTED_EVENT_TYPES),
                _const_tuple("EPHEMERAL_EVENT_TYPES", events.EPHEMERAL_EVENT_TYPES)]


def _alias_block(name: str, parts: list[str]) -> str:
    one_line = f"export type {name} = {' | '.join(parts)}"
    if len(one_line) <= 110:
        return one_line
    return f"export type {name} =\n" + "\n".join(f"  | {p}" for p in parts)


def _import_line(names: list[str], module: str) -> str:
    one_line = f"import type {{ {', '.join(names)} }} from './{module}'"
    if len(one_line) <= 110:
        return one_line
    return "import type {\n" + "".join(f"  {name},\n" for name in names) + f"}} from './{module}'"


def _const_tuple(name: str, values: Sequence[str]) -> str:
    return f"export const {name} = [\n" + "\n".join(f"  {_ts_literal(v)}," for v in values) + "\n] as const"


def render_all() -> dict[str, str]:
    """File name -> content for every generated file (index.ts included)."""
    registry = Registry(MODULES)
    files = {f"{name}.ts": ModuleWriter(registry, name).render() for name in MODULES}
    files["index.ts"] = HEADER + "\n\n" + "".join(f"export * from './{name}'\n" for name in MODULES)
    return files


def stale_files(out_dir: Path = OUT_DIR) -> list[str]:
    """Generated files that are missing, different or no longer produced."""
    files = render_all()
    stale = [name for name, text in files.items()
             if not (out_dir / name).is_file() or (out_dir / name).read_text(encoding="utf-8") != text]
    if out_dir.is_dir():
        stale += sorted(p.name for p in out_dir.glob("*.ts") if p.name not in files)
    return stale


def write_all(out_dir: Path = OUT_DIR) -> list[str]:
    files = render_all()
    out_dir.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, text in files.items():
        path = out_dir / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed.append(name)
    for path in sorted(out_dir.glob("*.ts")):
        if path.name not in files:
            path.unlink()
            changed.append(path.name)
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if any generated file would change")
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_files()
        for name in stale:
            print(f"out of date: {OUT_DIR.relative_to(REPO_ROOT) / name}")
        if stale:
            print("run: .venv/bin/python scripts/gen_ts_contracts.py")
        return 1 if stale else 0
    changed = write_all()
    print(f"{len(changed)} file(s) written" + (f": {', '.join(changed)}" if changed else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

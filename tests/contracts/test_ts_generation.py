"""scripts/gen_ts_contracts.py: the generated TypeScript in src/web/src/contracts/generated is current and mirrors
the pydantic models (CONTRACTS §4, §1.7 rule 6)."""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

from restaurantos.contracts import events

REPO = Path(__file__).resolve().parents[2]


def _load_generator():
    name = "restos_gen_ts_contracts"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, REPO / "scripts" / "gen_ts_contracts.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


gen = _load_generator()
FILES = gen.render_all()


def test_ts_generated_up_to_date():
    stale = gen.stale_files()
    assert stale == [], f"out of date: {stale}; run .venv/bin/python scripts/gen_ts_contracts.py"
    assert set(FILES) == {f"{m}.ts" for m in gen.MODULES} | {"index.ts"}
    for name, text in FILES.items():
        assert text.startswith("// GENERATED by scripts/gen_ts_contracts.py — do not edit\n"), name
    assert FILES["index.ts"].count("export * from './") == len(gen.MODULES)


def test_ts_event_payload_map_generated():
    text = FILES["events.ts"]
    assert "export type EventPayloads = {\n  [K in EventType]: {\n" in text
    for event_type, (_, model) in events.EVENT_SPECS.items():
        assert f"\n    '{event_type}': {model.__name__}\n" in text, event_type
    for const, expected in (("PERSISTED_EVENT_TYPES", events.PERSISTED_EVENT_TYPES),
                            ("EPHEMERAL_EVENT_TYPES", events.EPHEMERAL_EVENT_TYPES)):
        block = re.search(rf"export const {const} = \[\n(.*?)\n\] as const", text, re.S)
        assert block, const
        assert re.findall(r"'([^']+)'", block.group(1)) == list(expected)
    union = re.search(r"export type EventType =\n((?:  \| '[^']+'\n?)+)", text)
    assert union and re.findall(r"'([^']+)'", union.group(1)) == list(events.EVENT_TYPES)
    assert "import type { Approval, Incident, Plan," in text  # payloads reference the gm interfaces


def interface(name: str) -> dict[str, str]:
    for text in FILES.values():
        match = re.search(rf"export interface {name} {{\n(.*?)\n}}", text, re.S)
        if match:
            return dict(line.strip().split(": ", 1) for line in match.group(1).splitlines())
    raise AssertionError(f"no interface {name}")


def test_ts_interfaces_mirror_the_models():
    order = interface("Order")
    assert order["ready_biz"] == "string | null" and order["lines"] == "OrderLine[]"
    assert order["status"] == "OrderStatus" and order["caller_last4"] == "string | null"
    assert order["flags"] == "string[]" and order["created_at"] == "string"
    assert interface("Ticket")["undo_until"] == "string | null" and interface("EventEnvelope")["ts"] == "string"
    assert interface("CartOp")["item_code"] == "string | null" and interface("CartOp")["modifiers"] == "string[]"
    assert interface("OrderLine")["status"] == "OrderLineStatus" and "unit_price_cents" in interface("OrderLine")
    assert interface("Ingredient")["names"] == "Partial<Record<SpeakLang, string>>"
    assert interface("InventoryBandChangedPayload")["from"] == "Band"  # the JSON alias, not from_
    assert interface("SessionInfo")["sample"] == "true" and interface("EventEnvelope")["v"] == "1"
    assert interface("SessionStartedPayload")["lang_hint"] == "Lang | LangHint | null"
    assert interface("Candidate")["params"] == "Record<string, unknown>"
    assert interface("StatusReport")["degraded"] == "Partial<Record<DegradedComponent, ComponentState>>"
    assert interface("TenantState")["plans"] == "Plan[]" and interface("WsEvent")["kind"] == "'event'"
    assert "export type ClockSpeed = 0 | 1 | 10" in FILES["common.ts"]
    assert "export type EmptyBody = Record<string, never>" in FILES["api.ts"]
    assert "export type VoiceClientMessage =\n  | VoiceStart\n" in FILES["ws.ts"]
    assert "import type { Allergen, Channel, DialogueState, Lang, SpeakLang } from './common'" in FILES["orders.ts"]
    for text in FILES.values():  # no Python-only names leak into the web types
        assert "_ActionParamsMixin" not in text and "_AliasModel" not in text and "interface Model " not in text


def test_every_contract_model_rejects_unknown_fields():
    registry = gen.Registry(gen.MODULES)
    models = [m for module in gen.MODULES for m in registry.models[module]]
    assert len(models) > 150
    for model in models:
        assert model.model_config.get("extra") == "forbid", model.__name__
